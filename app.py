# 2. UI 表示ロジック
# ==========================================
st.title("🇰🇷 韓国語文法 学習アプリ (19-28課 完全版)")

# サイドバー
sorted_units = sorted(MASTER_DATA.keys(), key=int)
unit = st.sidebar.selectbox("単元を選択", sorted_units)
data = MASTER_DATA[unit]

tab_exp, tab_quiz = st.tabs(["📖 解説編", "📝 問題編"])

with tab_exp:
    st.markdown(f"## 第{unit}課: {data['title']}")
    mode = st.radio("表示モード", ["スタンダード", "発展編", "大阪弁"], horizontal=True)
    st.divider()
    if mode == "スタンダード": st.info(data['exp_std'])
    elif mode == "発展編": st.success(data.get('exp_adv', "専門解説準備中"))
    else: st.warning(data.get('exp_osa', "大阪弁解説準備中"))

with tab_quiz:
    st.markdown("### 練習問題")
    q_type = st.radio("形式を選択", ["概念の穴埋め", "活用4択問題", "韓国語作文"], horizontal=True)
    st.divider()

    if q_type == "概念の穴埋め":
        st.write(f"#### Q: {data['q_fill']['q']}")
        ans = st.text_input("回答を入力", key=f"f_{unit}")
        if st.button("採点"):
            if ans.strip() == data['q_fill']['a']: st.success("🎉 正解！学習目標の核心を掴んでいます。")
            else: st.error(f"❌ 正解は「{data['q_fill']['a']}」です。解説を読み直しましょう。")
    
    elif q_type == "活用4択問題":
        for i, q_item in enumerate(data['q_choice']):
            st.write(f"#### {q_item['q']}")
            choice = st.radio(f"選択肢 {i}", q_item['c'], key=f"c_{unit}_{i}")
            if st.button(f"採点 {i+1}", key=f"b_c_{i}"):
                if choice == q_item['a']: st.success("🎉 正解！")
                else: st.error(f"❌ 正解は「{q_item['a']}」です。")

    elif q_type == "韓国語作文":
        for i, q_item in enumerate(data['q_write']):
            st.write(f"#### {q_item['q']}")
            st.caption(f"💡 ヒント：{q_item['hint']}")
            write_ans = st.text_input(f"作文入力 {i}", key=f"w_{unit}_{i}")
            if st.button(f"採点 {i+1}", key=f"b_w_{i}"):
                if write_ans.replace(" ","") == q_item['a'].replace(" ",""): st.success("✅ 正解！")
                else: st.error(f"❌ 正解は「{q_item['a']}」です。")
