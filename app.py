if "scores" not in st.session_state:
    st.session_state.scores = {}  # {unit: {qkey: True/False}}


def record_answer(unit: str, qkey: str, is_correct: bool):
    if unit not in st.session_state.scores:
        st.session_state.scores[unit] = {}
    st.session_state.scores[unit][qkey] = is_correct


def get_unit_score(unit: str):
    data = st.session_state.scores.get(unit, {})
    if not data:
        return 0, 0
    correct = sum(1 for v in data.values() if v)
    return correct, len(data)


def get_total_score():
    total_c = sum(
        sum(1 for v in d.values() if v)
        for d in st.session_state.scores.values()
    )
    total_t = sum(len(d) for d in st.session_state.scores.values())
    return total_c, total_t


