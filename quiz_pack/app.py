data = MASTER_DATA[unit]

tab_exp, tab_quiz = st.tabs(["📖 解説編", "📝 問題編"])

with tab_exp:
    st.markdown(f"## 第{unit}課: {data['title']}")
    m_exp = st.radio("表示モード切替", ["スタンダード", "発展編", "大阪弁"], horizontal=True)
    st.divider()
    if m_exp == "スタンダード": st.info(data['exp_std'])
    elif m_exp == "発展編": st.success(data['exp_adv'])
    else: st.warning(data['exp_osa'])

with tab_quiz:
    st.markdown(f"## 第{unit}課 練習問題")
    m_quiz = st.radio("形式を選択", ["概念の穴埋め", "活用4択問題(3題)", "韓国語作文(3題)"], horizontal=True)
    st.divider()

    if m_quiz == "概念の穴埋め":
        st.write(f"#### Q: {data['q_fill']['q']}")
        ans_fill = st.text_input("回答を入力", key=f"f_{unit}")
        if st.button("採点", key="b_f"):
            if ans_fill.strip() == data['q_fill']['a']: st.success("🎉 正解！学習目標をよく理解しています。")
            else: st.error(f"❌ 正解は「{data['q_fill']['a']}」です。解説を再読しましょう。")

    elif m_quiz == "活用4択問題(3題)":
        for i, q_item in enumerate(data['q_choice']):
            st.write(f"#### {q_item['q']}")
            ans = st.radio(f"選択肢 {i}", q_item['c'], key=f"c_{unit}_{i}")
            if st.button(f"採点 {i+1}", key=f"b_c_{i}"):
                if ans == q_item['a']: st.success("🎉 正解！")
                else: st.error(f"❌ 正解は「{q_item['a']}」です。")
            st.divider()

    elif m_quiz == "韓国語作文(3題)":
        for i, q_item in enumerate(data['q_write']):
            st.write(f"#### {q_item['q']}")
            st.caption(f"💡 ヒント：{q_item['hint']}")
            ans = st.text_input(f"回答入力 {i}", key=f"w_{unit}_{i}")
            if st.button(f"採点 {i+1}", key=f"b_w_{i}"):
                u_clean = ans.replace(" ", "").replace("　", "")
                c_clean = q_item['a'].replace(" ", "").replace("　", "")
                if u_clean == c_clean: st.success(f"✅ 正解！ (正規：{q_item['a']})")
                else: st.error(f"❌ 正解は「{q_item['a']}」です。")
            st.divider()